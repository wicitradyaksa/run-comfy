"""Automatic QA for finished ads.

1. Technical checks (always): right size, has video/audio, sane duration, loudness near target.
2. Vision review (when an Anthropic key is available): Claude scores sampled frames against a rubric
   and the brand rules, and names the stage most likely responsible for a problem so only that stage
   is re-rendered.
"""
from __future__ import annotations

import base64
import os
from pathlib import Path

from pydantic import BaseModel, Field

from .. import media
from .brand import ASPECTS, Brand


class QAReport(BaseModel):
    score: int = Field(description="Overall publishability 0-10 (10 = ready to run as a paid ad)")
    issues: list[str] = Field(description="Concrete visible problems, most severe first")
    brand_violations: list[str] = Field(description="Anything that breaks the brand rules or banned claims")
    suspect_stage: str = Field(description="The pipeline stage most likely to fix the worst issue if "
                                           "re-rendered, or 'none'")
    summary: str = Field(description="One sentence verdict")


RUBRIC = """You are the final quality gate for paid social ads generated by an AI pipeline. \
You see frames sampled across one finished ad (in order) and its script.

Score 0-10 for publishability. Deduct heavily for: distorted or extra fingers/limbs, melted or \
asymmetric faces, warped product shape or garbled product label, unreadable or misspelled burned-in \
text, captions covering the face or product, obvious AI artifacts, off-brand look, anything violating \
the brand rules. Placeholder / flat demo graphics are fine to score on composition only.

Pipeline stages you may blame (re-rendering one of these with a new seed is the fix): {stages}. \
Pick the single stage whose re-render would most improve the ad, or "none"."""


def technical_checks(path: Path, aspect: str, kind: str = "video", target_lufs: float = -14.0,
                     min_s: float = 3.0, max_s: float = 90.0) -> list[str]:
    problems = []
    w, h = ASPECTS.get(aspect, (0, 0))
    if kind == "image":
        from PIL import Image

        with Image.open(path) as im:
            if (im.width, im.height) != (w, h):
                problems.append(f"image is {im.width}x{im.height}, expected {w}x{h}")
        return problems
    if not media.has_stream(path, "video"):
        return ["no video stream"]
    if media.video_size(path) != (w, h):
        problems.append(f"video is {media.video_size(path)}, expected {(w, h)}")
    d = media.duration(path)
    if not min_s <= d <= max_s:
        problems.append(f"duration {d:.1f}s outside {min_s}-{max_s}s")
    lufs = media.loudness(path)
    if lufs is None:
        problems.append("no audio track")
    elif abs(lufs - target_lufs) > 2.0:
        problems.append(f"loudness {lufs:.1f} LUFS, target {target_lufs}")
    return problems


async def vision_review(frames: list[Path], brand: Brand, script: str, stages: list[str], client,
                        model: str) -> QAReport:
    content = []
    for f in frames:
        mt = "image/png" if f.suffix.lower() == ".png" else "image/jpeg"
        content.append({"type": "image", "source": {"type": "base64", "media_type": mt,
                                                    "data": base64.standard_b64encode(f.read_bytes()).decode()}})
    rules = [f"Brand: {brand.name}. Tone: {brand.tone}."]
    if brand.banned:
        rules.append("Banned words/claims: " + ", ".join(brand.banned))
    content.append({"type": "text", "text": "\n".join(rules) + f"\n\nScript:\n{script or '(static ad)'}"})
    resp = await client.beta.messages.parse(
        model=model, max_tokens=4000,
        system=RUBRIC.format(stages=", ".join(stages) or "none"),
        messages=[{"role": "user", "content": content}],
        output_format=QAReport,
        output_config={"effort": "low"},
        betas=["server-side-fallback-2026-07-01"], fallbacks="default",
    )
    if resp.parsed_output is None:
        raise ValueError(f"QA judge returned nothing (stop_reason={resp.stop_reason})")
    rep = resp.parsed_output
    if rep.suspect_stage not in stages:
        rep.suspect_stage = "none"
    return rep


async def review(path: Path, *, aspect: str, kind: str, brand: Brand, script: str, stages: list[str],
                 threshold: int, target_lufs: float, work_dir: Path, client=None,
                 model: str = "claude-opus-5-5") -> dict:
    tech = technical_checks(path, aspect, kind, target_lufs)
    result = {"technical": tech, "score": None, "issues": [], "brand_violations": [], "suspect_stage": "none",
              "summary": "", "vision": False}
    if client is None and os.environ.get("ANTHROPIC_API_KEY"):
        import anthropic

        client = anthropic.AsyncAnthropic()
    if client is not None and not tech:
        frames = [path] if kind == "image" else media.extract_frames(path, work_dir / "qa_frames", 4)
        rep = await vision_review(frames, brand, script, stages, client, model)
        result.update(rep.model_dump(), vision=True)
    result["passed"] = not tech and (result["score"] is None or result["score"] >= threshold) \
        and not result["brand_violations"]
    return result
