"""Provisioning from workflow manifests: a Docker image with pinned custom nodes, and a network
volume seeded with the exact model files (sha256-checked). Removes most hand setup on RunPod."""
from __future__ import annotations

import asyncio
import base64
import logging
import re
import time
from pathlib import Path

import httpx

from .registry import Workflow

log = logging.getLogger("run_comfy")


def collect(registry: dict[str, Workflow], names: list[str] | None = None) -> tuple[list[dict], list[dict]]:
    """De-duplicated (models, custom_nodes) across the selected workflows."""
    models, nodes = {}, {}
    for name, wf in registry.items():
        if names and name not in names:
            continue
        for m in wf.models:
            models.setdefault(m["path"], m)
        for n in wf.custom_nodes:
            nodes.setdefault(n["repo"], n)
    return list(models.values()), list(nodes.values())


def dockerfile(registry: dict[str, Workflow], base_image: str, comfy_dir: str = "/comfyui",
               bake_models: bool = False, names: list[str] | None = None) -> str:
    models, nodes = collect(registry, names)
    lines = [
        "# syntax=docker/dockerfile:1.7",
        "# Generated by `run_comfy build-image` from workflows/*/manifest.toml - edit the manifests, not this.",
        f"FROM {base_image}",
        "RUN apt-get update && apt-get install -y --no-install-recommends git && rm -rf /var/lib/apt/lists/*",
    ]
    for n in nodes:
        name = n.get("name") or re.sub(r"\.git$", "", n["repo"].rstrip("/").split("/")[-1])
        commit = n.get("commit", "")
        lines.append(
            f"RUN git clone {n['repo']} {comfy_dir}/custom_nodes/{name} && cd {comfy_dir}/custom_nodes/{name} "
            + (f"&& git checkout {commit} " if commit else "")
            + "&& (test ! -f requirements.txt || pip install --no-cache-dir -r requirements.txt)")
    if bake_models:
        for m in models:
            chk = f"--checksum=sha256:{m['sha256']} " if m.get("sha256") else ""
            lines.append(f"ADD {chk}{m['url']} {comfy_dir}/{m['path']}")
    return "\n".join(lines) + "\n"


SEED_SCRIPT = r'''
import hashlib, http.server, json, os, threading, urllib.request
STATUS = {"state": "running", "done": [], "failed": [], "current": None, "bytes": 0}
os.makedirs("/status", exist_ok=True)
def save():
    open("/status/status.json.tmp", "w").write(json.dumps(STATUS)); os.replace("/status/status.json.tmp", "/status/status.json")
save()
class H(http.server.SimpleHTTPRequestHandler):
    def __init__(s, *a, **k): super().__init__(*a, directory="/status", **k)
    def log_message(s, *a): pass
threading.Thread(target=http.server.ThreadingHTTPServer(("0.0.0.0", 8000), H).serve_forever, daemon=True).start()
def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for c in iter(lambda: f.read(1 << 22), b""): h.update(c)
    return h.hexdigest()
for m in MODELS:
    dest = os.path.join(ROOT, m["path"]); STATUS["current"] = m["path"]; save()
    try:
        if os.path.exists(dest) and (not m.get("sha256") or sha(dest) == m["sha256"]):
            STATUS["done"].append(m["path"]); continue
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        req = urllib.request.Request(m["url"], headers={"User-Agent": "run-comfy-seed"})
        if "huggingface.co" in m["url"] and os.environ.get("HF_TOKEN"):
            req.add_header("Authorization", "Bearer " + os.environ["HF_TOKEN"])
        if "civitai.com" in m["url"] and os.environ.get("CIVITAI_TOKEN"):
            req.add_header("Authorization", "Bearer " + os.environ["CIVITAI_TOKEN"])
        with urllib.request.urlopen(req, timeout=60) as r, open(dest + ".part", "wb") as f:
            while True:
                c = r.read(1 << 22)
                if not c: break
                f.write(c); STATUS["bytes"] += len(c)
                if STATUS["bytes"] % (1 << 28) < (1 << 22): save()
        if m.get("sha256") and sha(dest + ".part") != m["sha256"]:
            os.remove(dest + ".part"); raise ValueError("sha256 mismatch")
        os.replace(dest + ".part", dest); STATUS["done"].append(m["path"])
    except Exception as e:
        STATUS["failed"].append({"path": m["path"], "error": str(e)[:300]})
    save()
STATUS["state"] = "finished"; STATUS["current"] = None; save()
threading.Event().wait()
'''


def seed_command(models: list[dict], root: str = "/workspace") -> str:
    import json

    script = f"MODELS = {json.dumps(models)}\nROOT = {root!r}\n" + SEED_SCRIPT
    b64 = base64.b64encode(script.encode()).decode()
    return f"bash -c 'echo {b64} | base64 -d > /seed.py && python3 -u /seed.py'"


async def seed_volume(pods, models: list[dict], image: str = "python:3.12-slim", poll_s: float = 15,
                      timeout_s: float = 4 * 3600, env: dict | None = None,
                      transport: httpx.AsyncBaseTransport | None = None) -> dict:
    """Start a throwaway pod on the network volume, download every model, verify, terminate."""
    if not models:
        return {"state": "finished", "done": [], "failed": []}
    pid, _ = await pods.create(99, name=f"{pods.cfg.name_prefix}-seed", image_name=image,
                               docker_args=seed_command(models), ports="8000/http",
                               container_disk_in_gb=10, env=env or None, start_ssh=False)
    url = f"https://{pid}-8000.proxy.runpod.net/status.json"
    status: dict = {}
    t = time.monotonic()
    try:
        async with httpx.AsyncClient(timeout=20, transport=transport) as c:
            while time.monotonic() - t < timeout_s:
                try:
                    r = await c.get(url)
                    if r.status_code == 200:
                        status = r.json()
                        log.info("seeding: %d/%d done, %.1f GB, now %s", len(status["done"]), len(models),
                                 status["bytes"] / 1e9, status.get("current"))
                        if status["state"] == "finished":
                            return status
                except (httpx.HTTPError, ValueError):
                    pass
                await asyncio.sleep(poll_s)
        raise TimeoutError(f"seeding not finished after {timeout_s:.0f}s: {status}")
    finally:
        await pods.terminate(pid)
